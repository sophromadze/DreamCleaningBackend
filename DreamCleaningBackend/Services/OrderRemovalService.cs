using DreamCleaningBackend.Data;
using DreamCleaningBackend.Helpers;
using DreamCleaningBackend.Models;
using DreamCleaningBackend.Models.Billing;
using DreamCleaningBackend.Services.Interfaces;
using Microsoft.EntityFrameworkCore;

namespace DreamCleaningBackend.Services
{
    /// <summary>A removal the admin can act on. Mapped to 400 by every caller.</summary>
    public class OrderRemovalException : Exception
    {
        public OrderRemovalException(string message) : base(message) { }
    }

    /// <summary>What <see cref="IOrderRemovalService.CheckAsync(Order)"/> found for one order.</summary>
    public sealed class OrderRemovalCheck
    {
        public int OrderId { get; init; }

        /// <summary>
        /// The order is in a recurring plan (generated by one, or the plan's source). Only those
        /// get the full money check — see <see cref="OrderRemovalService"/>.
        /// </summary>
        public bool InSeries { get; init; }

        /// <summary>Null = may be deleted or skipped. Otherwise a short reason ("Paid — refund first").</summary>
        public string? BlockedReason { get; set; }

        public bool CanRemove => BlockedReason == null;

        /// <summary>Cleaners who were sent the assignment email. Never blocks — named so somebody tells them.</summary>
        public List<string> NotifiedCleaners { get; } = new();

        /// <summary>An admin edited the order (an OrderUpdateHistories row exists). Never blocks a removal.</summary>
        public bool HandEdited { get; set; }

        public bool HasPaymentReference { get; set; }
    }

    /// <summary>What a removal left for the caller to do after its transaction commits.</summary>
    public sealed class OrderRemovalOutcome
    {
        public List<string> PhotoUrls { get; } = new();
        public List<string> Warnings { get; } = new();
    }

    public interface IOrderRemovalService
    {
        Task<OrderRemovalCheck> CheckAsync(Order order);
        Task<Dictionary<int, OrderRemovalCheck>> CheckAsync(IReadOnlyCollection<Order> orders);

        /// <summary>
        /// Makes every unpaid payment attempt on the order unusable (individual intent, an open
        /// "Pay all" batch, an open part-payment request). Call while holding the customer lock.
        /// </summary>
        Task CloseOpenPaymentAttemptsAsync(Order order);

        /// <summary>
        /// Deletes the order and every row that would otherwise refuse to let it go. The caller owns
        /// the transaction. <paramref name="alsoRemoving"/> names the other orders deleted in the
        /// same operation, so a series' source is never moved onto one of them.
        /// </summary>
        Task<OrderRemovalOutcome> RemoveAsync(Order order, int adminUserId, IReadOnlySet<int>? alsoRemoving = null);

        /// <summary>Deletes uploaded photo files. Call only after the transaction committed.</summary>
        void DeleteStoredFiles(IEnumerable<string> publicUrls);

        Task<Dictionary<int, string>> CleanerNamesAsync(IReadOnlyCollection<int> cleanerIds);
    }

    /// <summary>
    /// ONE answer to "may this order be deleted or skipped?" — shared by permanent delete, Skip,
    /// and Stop recurrence's "delete the unfinished cleanings" option, so the three cannot drift.
    ///
    /// ══ WHAT BLOCKS (orders in a recurring plan) ══
    ///
    /// Real activity only: money that arrived (paid, part-paid, a collected top-up, a manual
    /// payment record, a refund), the order being on a commercial invoice or in a paid / processing
    /// combined payment, a saved-card charge in flight, cleaner wages paid, or status Done.
    ///
    /// ══ WHAT DOES NOT (2026-10) ══
    ///
    /// An admin edit (an <see cref="OrderUpdateHistory"/> row is written by EVERY edit, even a $0
    /// date move), an unpaid payment link or intent (closed as part of the removal), a copied or
    /// even notified cleaner assignment (removed; a notified cleaner is NAMED in the warnings so
    /// somebody tells them), notification logs, and merely belonging to a plan. The old guard
    /// blocked on the first three, which made an unpaid, unstaffed occurrence undeletable as soon
    /// as anybody had touched it.
    ///
    /// ══ ORDERS OUTSIDE A PLAN ══
    ///
    /// Keep the SuperAdmin hard delete they always had ("no Stripe refund is issued — cancel
    /// first"): only the rows the database itself would refuse — a non-void commercial invoice, a
    /// paid/processing combined payment, a saved-card charge in flight — are checked for them.
    ///
    /// Automatic Regenerate (schedule edits) stays STRICTER on purpose: it also keeps hand-edited
    /// and notified occurrences, because a machine should not cancel orders a person touched. It
    /// reads the same check and adds those two facts itself.
    /// </summary>
    public class OrderRemovalService : IOrderRemovalService
    {
        private readonly ApplicationDbContext _context;
        private readonly IRecurringCustomerPaymentService _payments;
        private readonly IStripeService? _stripe;
        private readonly IAuditService? _audit;
        private readonly IConfiguration? _configuration;
        private readonly ILogger<OrderRemovalService>? _logger;

        public OrderRemovalService(
            ApplicationDbContext context,
            IRecurringCustomerPaymentService payments,
            IStripeService? stripe = null,
            IAuditService? audit = null,
            IConfiguration? configuration = null,
            ILogger<OrderRemovalService>? logger = null)
        {
            _context = context;
            _payments = payments;
            _stripe = stripe;
            _audit = audit;
            _configuration = configuration;
            _logger = logger;
        }

        public async Task<OrderRemovalCheck> CheckAsync(Order order) =>
            (await CheckAsync(new[] { order }))[order.Id];

        public async Task<Dictionary<int, OrderRemovalCheck>> CheckAsync(IReadOnlyCollection<Order> orders)
        {
            var ids = orders.Select(o => o.Id).ToList();

            var templateIds = await _context.RecurringOrderSeries
                .Where(s => ids.Contains(s.TemplateOrderId)).Select(s => s.TemplateOrderId).ToListAsync();
            var invoices = await _context.CommercialInvoiceOrders
                .Where(i => ids.Contains(i.OrderId) && i.Invoice!.Status != Models.Commercial.InvoiceStatus.Void)
                .Select(i => new { i.OrderId, i.Invoice!.InvoiceNumber }).ToListAsync();
            var batches = await _context.OrderPaymentBatchItems
                .Where(i => ids.Contains(i.OrderId)
                    && (i.Batch!.Status == OrderPaymentBatchStatus.Paid || i.Batch!.Status == OrderPaymentBatchStatus.Processing))
                .Select(i => new { i.OrderId, i.OrderPaymentBatchId, i.Batch!.Status }).ToListAsync();
            var lockKeys = ids.Select(BillingPaymentAttempt.OrderObligationKey).ToList();
            var savedCardBusy = await _context.BillingPaymentAttempts
                .Where(a => a.ActiveLockKey != null && lockKeys.Contains(a.ActiveLockKey))
                .Select(a => a.ActiveLockKey!).ToListAsync();
            var refunded = await _context.OrderRefunds.Where(r => ids.Contains(r.OrderId)).Select(r => r.OrderId).ToListAsync();
            var paidSlices = await _context.OrderPartialPayments
                .Where(p => ids.Contains(p.OrderId) && p.Status == OrderPartialPaymentStatus.Paid)
                .Select(p => p.OrderId).ToListAsync();
            var collectedTopUps = await _context.OrderUpdateHistories
                .Where(h => ids.Contains(h.OrderId)).Where(OrderAdditionalCharge.WasCollected)
                .Select(h => h.OrderId).ToListAsync();
            var edited = await _context.OrderUpdateHistories
                .Where(h => ids.Contains(h.OrderId)).Select(h => h.OrderId).Distinct().ToListAsync();
            // The facts first, with no join, so a row is never lost to a missing cleaner record;
            // names are looked up separately and only for display.
            var cleaners = await _context.OrderCleaners
                .Where(c => ids.Contains(c.OrderId))
                .Select(c => new
                {
                    c.OrderId,
                    c.CleanerId,
                    WagesPaid = c.IsPaid || c.PaidAt != null || (c.PaidAmount ?? 0) > 0,
                    Notified = c.AssignmentNotificationSentAt != null
                }).ToListAsync();
            var notifiedIds = cleaners.Where(c => c.Notified).Select(c => c.CleanerId).Distinct().ToList();
            var names = await CleanerNamesAsync(notifiedIds);
            var paidSlots = await _context.OrderUnassignedPayouts
                .Where(p => ids.Contains(p.OrderId) && (p.IsPaid || p.PaidAt != null))
                .Select(p => p.OrderId).ToListAsync();

            var result = new Dictionary<int, OrderRemovalCheck>();
            foreach (var o in orders)
            {
                var check = new OrderRemovalCheck
                {
                    OrderId = o.Id,
                    InSeries = o.RecurringSeriesId != null || o.IsGeneratedByRecurringSeries || templateIds.Contains(o.Id),
                    HandEdited = edited.Contains(o.Id),
                    HasPaymentReference = !string.IsNullOrWhiteSpace(o.PaymentReference)
                };
                check.NotifiedCleaners.AddRange(cleaners.Where(c => c.OrderId == o.Id && c.Notified)
                    .Select(c => names.GetValueOrDefault(c.CleanerId) ?? CleanerName(c.CleanerId, null, null)));

                // Rows the database itself would refuse to release — checked for EVERY order.
                var invoice = invoices.FirstOrDefault(i => i.OrderId == o.Id);
                var batch = batches.FirstOrDefault(b => b.OrderId == o.Id);
                if (invoice != null)
                    check.BlockedReason = $"On invoice {invoice.InvoiceNumber} — void it or take the cleaning off it first";
                else if (batch != null)
                    check.BlockedReason = batch.Status == OrderPaymentBatchStatus.Paid
                        ? $"Paid in combined payment #{batch.OrderPaymentBatchId} — refund first"
                        : $"Combined payment #{batch.OrderPaymentBatchId} is processing — wait for it to finish";
                else if (savedCardBusy.Contains(BillingPaymentAttempt.OrderObligationKey(o.Id)))
                    check.BlockedReason = "A saved-card charge is in progress";

                // Money and work — the full check, for orders in a recurring plan.
                else if (check.InSeries)
                {
                    if (OrderStatuses.Is(o.Status, OrderStatuses.Done))
                        check.BlockedReason = "Done — completed cleanings are kept";
                    else if (OrderStatuses.IsRefunded(o.Status) || o.TotalRefundedAmount != 0 || refunded.Contains(o.Id))
                        check.BlockedReason = "Refunded — kept as a payment record";
                    else if (o.IsPaid || o.PaidAt != null || o.InvoicePaidAt != null)
                        check.BlockedReason = "Paid — refund first";
                    else if (o.ManualPaymentRecordedAt != null)
                        check.BlockedReason = $"Paid ({o.PaymentMethod}, recorded manually) — reverse the payment first";
                    else if (o.AmountPaid > 0 || paidSlices.Contains(o.Id))
                        check.BlockedReason = $"Part-paid (${o.AmountPaid:0.00}) — refund first";
                    else if (collectedTopUps.Contains(o.Id))
                        check.BlockedReason = "An extra amount was paid on it — refund first";
                    else if (cleaners.Any(c => c.OrderId == o.Id && c.WagesPaid) || paidSlots.Contains(o.Id))
                        check.BlockedReason = "Cleaner wages paid for it — reverse the payout first";
                }

                result[o.Id] = check;
            }
            return result;
        }

        public async Task CloseOpenPaymentAttemptsAsync(Order order)
        {
            try
            {
                // Retry's authoritative Stripe check and whole-batch cancellation: merely opening
                // the payment page (or Pay all) must not permanently reserve a cleaning.
                await _payments.PrepareIndividualPaymentAsync(order.Id);
            }
            catch (CombinedPaymentException ex) { throw new OrderRemovalException(ex.Message); }
            catch (Exception ex)
            {
                _logger?.LogWarning(ex, "Could not safely close payment attempts for order {OrderId}", order.Id);
                throw new OrderRemovalException("Could not safely close the open payment link for this cleaning. Please retry.");
            }

            // A part-payment request the customer already opened has its own intent. The rows go
            // with the order (cascade); the intent has to be made unusable first.
            var open = await _context.OrderPartialPayments
                .Where(p => p.OrderId == order.Id && p.Status == OrderPartialPaymentStatus.Pending && p.PaymentIntentId != null)
                .ToListAsync();
            foreach (var request in open)
            {
                if (_stripe == null)
                    throw new OrderRemovalException("Withdraw the open payment request on this order first.");
                try { await RecurringPaymentAttemptGuard.CancelOpenAsync(_stripe, request.PaymentIntentId!); }
                catch (CombinedPaymentException ex) { throw new OrderRemovalException(ex.Message); }
                catch (Exception ex)
                {
                    _logger?.LogWarning(ex, "Could not cancel part-payment intent for order {OrderId}", order.Id);
                    throw new OrderRemovalException("Could not safely close the open payment request on this cleaning. Please retry.");
                }
            }
        }

        public async Task<OrderRemovalOutcome> RemoveAsync(Order order, int adminUserId, IReadOnlySet<int>? alsoRemoving = null)
        {
            var outcome = new OrderRemovalOutcome();
            var orderId = order.Id;

            // ── A plan's source: RecurringOrderSeries.TemplateOrderId is RESTRICT ─────────────
            foreach (var series in await _context.RecurringOrderSeries.Where(s => s.TemplateOrderId == orderId).ToListAsync())
            {
                if (series.StoppedAt == null)
                    throw new OrderRemovalException(
                        "This order is the source of a recurring plan that is still running. Stop the recurrence first.");

                // The stopped plan keeps listing its history: its source moves to the earliest order
                // it still has. Only a plan with nothing left is removed.
                var replacement = await _context.Orders
                    .Where(o => o.RecurringSeriesId == series.Id && o.Id != orderId)
                    .OrderBy(o => o.ServiceDate).ThenBy(o => o.ServiceTime).ThenBy(o => o.Id)
                    .Select(o => o.Id)
                    .ToListAsync();
                var newTemplateId = replacement.FirstOrDefault(id => alsoRemoving == null || !alsoRemoving.Contains(id));
                if (newTemplateId != 0)
                {
                    series.TemplateOrderId = newTemplateId;
                    series.UpdatedAt = DateTime.UtcNow;
                    series.UpdatedByUserId = adminUserId;
                    await LogSeriesAsync(series.Id, "RecurringSeriesSourceMoved",
                        new { FromOrderId = orderId, ToOrderId = newTemplateId, Reason = "Source order deleted" }, adminUserId);
                }
                else
                {
                    _context.RecurringOrderSeries.Remove(series);
                    await LogSeriesAsync(series.Id, "RecurringSeriesRemoved",
                        new { SourceOrderId = orderId, Reason = "Its source order was deleted and it had no other orders" }, adminUserId);
                }
            }
            // Re-point before the delete is sent, so the RESTRICT FK never sees a dangling source.
            await _context.SaveChangesAsync();

            // Cleaning photos: the FK would only null OrderId, leaving unassigned photos — delete
            // rows here and files after the commit.
            var photos = await _context.UserCleaningPhotos.Where(p => p.OrderId == orderId).ToListAsync();
            outcome.PhotoUrls.AddRange(photos.Select(p => p.PhotoUrl).Where(u => !string.IsNullOrWhiteSpace(u)));
            _context.UserCleaningPhotos.RemoveRange(photos);

            // RESTRICT: gift-card usages (the card balance stays as already deducted), the links of
            // VOID commercial invoices (a live one blocked in CheckAsync), and the items of
            // unpaid/cancelled combined payments (their intents were closed above).
            _context.GiftCardUsages.RemoveRange(await _context.GiftCardUsages.Where(g => g.OrderId == orderId).ToListAsync());
            _context.CommercialInvoiceOrders.RemoveRange(await _context.CommercialInvoiceOrders.Where(i => i.OrderId == orderId).ToListAsync());
            _context.OrderPaymentBatchItems.RemoveRange(await _context.OrderPaymentBatchItems.Where(i => i.OrderId == orderId).ToListAsync());

            // No cascade on OrderId.
            _context.NotificationLogs.RemoveRange(await _context.NotificationLogs.Where(n => n.OrderId == orderId).ToListAsync());

            // Copied cleaner assignments go with the order (cascade). A cleaner who was emailed is
            // named, because nothing here tells them the job is off.
            var notifiedIds = await _context.OrderCleaners
                .Where(c => c.OrderId == orderId && c.AssignmentNotificationSentAt != null)
                .Select(c => c.CleanerId).ToListAsync();
            var names = await CleanerNamesAsync(notifiedIds);
            var notified = notifiedIds.Select(id => names.GetValueOrDefault(id) ?? CleanerName(id, null, null)).ToList();
            if (notified.Count > 0)
                outcome.Warnings.Add(NotifiedWarning(order, notified));

            // Services, extras, cleaner assignments, update history, part-payment requests, regular
            // customer invoices, refunds, payout slots, admin notes and reminder acks all cascade.
            // BubblePointsHistory / CleanerNote / UserSpecialOffer order refs are SET NULL.
            _context.Orders.Remove(order);
            await _context.SaveChangesAsync();
            return outcome;
        }

        /// <summary>Display names by cleaner id. Ids with no cleaner record are simply absent.</summary>
        public async Task<Dictionary<int, string>> CleanerNamesAsync(IReadOnlyCollection<int> cleanerIds)
        {
            if (cleanerIds.Count == 0) return new Dictionary<int, string>();
            return (await _context.Cleaners.AsNoTracking()
                    .Where(c => cleanerIds.Contains(c.Id))
                    .Select(c => new { c.Id, c.FirstName, c.LastName }).ToListAsync())
                .ToDictionary(c => c.Id, c => CleanerName(c.Id, c.FirstName, c.LastName));
        }

        public static string CleanerName(int cleanerId, string? firstName, string? lastName)
        {
            var name = $"{firstName} {lastName}".Trim();
            return name.Length > 0 ? name : $"Cleaner #{cleanerId}";
        }

        public static string NotifiedWarning(Order order, IEnumerable<string> cleanerNames) =>
            $"Order #{order.Id} ({order.ServiceDate:ddd MMM d}): {string.Join(", ", cleanerNames.Select(n => n.Trim()))} "
            + "had been sent the assignment — let them know the job is off.";

        public void DeleteStoredFiles(IEnumerable<string> publicUrls)
        {
            var basePath = _configuration?["FileUpload:Path"];
            if (string.IsNullOrWhiteSpace(basePath)) return;
            foreach (var url in publicUrls)
            {
                if (string.IsNullOrWhiteSpace(url)) continue;
                var fullPath = Path.Combine(basePath, url.TrimStart('/'));
                try
                {
                    if (File.Exists(fullPath)) File.Delete(fullPath);
                }
                catch (Exception ex)
                {
                    // The rows are gone; a leftover file is housekeeping, not a failed delete.
                    _logger?.LogWarning(ex, "Could not delete uploaded file {Path}", fullPath);
                }
            }
        }

        /// <summary>
        /// Turns a foreign-key refusal into something an admin can act on. Every RESTRICT FK into
        /// Orders is cleared or checked above, so reaching this means a row nobody expected — the
        /// caller logs the full exception.
        /// </summary>
        public static string Describe(DbUpdateException ex, int orderId)
        {
            var detail = ex.InnerException?.Message ?? ex.Message;
            if (detail.Contains("RecurringOrderSeries", StringComparison.OrdinalIgnoreCase))
                return $"Order #{orderId} is still the source of a recurring plan. Stop the recurrence first.";
            if (detail.Contains("CommercialInvoiceOrders", StringComparison.OrdinalIgnoreCase))
                return $"Order #{orderId} is on a commercial invoice. Void the invoice or take the cleaning off it first.";
            if (detail.Contains("OrderPaymentBatchItems", StringComparison.OrdinalIgnoreCase))
                return $"Order #{orderId} is part of a combined payment. Refund or cancel that payment first.";
            if (detail.Contains("GiftCardUsages", StringComparison.OrdinalIgnoreCase))
                return $"Order #{orderId} still has a gift-card usage attached. Please retry.";
            if (detail.Contains("foreign key", StringComparison.OrdinalIgnoreCase))
                return $"Order #{orderId} could not be deleted because another record still points at it. The details were logged.";
            return $"Order #{orderId} could not be deleted because the database refused the change. The details were logged.";
        }

        private Task LogSeriesAsync(int seriesId, string action, object payload, int adminUserId) =>
            _audit == null
                ? Task.CompletedTask
                : _audit.LogActionAsync(AuditEntityTypes.RecurringOrderSeriesAction, seriesId, action,
                    oldValues: null, newValues: payload, actingUserId: adminUserId);
    }
